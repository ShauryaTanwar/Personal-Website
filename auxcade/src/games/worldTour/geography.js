export function pointInPolygon(lon, lat, polygon) {
    let inside = false;
    for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
        const [xi, yi] = polygon[i], [xj, yj] = polygon[j];
        if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi)
            inside = !inside;
    }
    return inside;
}
export function spherePoint(lat, lon) { const p = lat * Math.PI / 180, l = lon * Math.PI / 180; return [Math.cos(p) * Math.sin(l), Math.sin(p), Math.cos(p) * Math.cos(l)]; }
export function distanceKm(a, b) { const u = spherePoint(a.lat, a.lon), v = spherePoint(b.lat, b.lon); return Math.acos(Math.max(-1, Math.min(1, u.reduce((s, x, i) => s + x * v[i], 0)))) * 6371; }
export function geographicCenter(locations) {
    const sum = locations.reduce((a, l) => spherePoint(l.lat, l.lon).map((v, i) => v + a[i]), [0, 0, 0]);
    if (Math.hypot(...sum) < 1e-6)
        return null;
    return { lat: Math.atan2(sum[1], Math.hypot(sum[0], sum[2])) * 180 / Math.PI, lon: Math.atan2(sum[0], sum[2]) * 180 / Math.PI };
}
